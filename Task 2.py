# ------------------------------------------------------------
# 2. LOAD THE PRETRAINED AI MODEL
# ------------------------------------------------------------

print("Loading AI model...")

model = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2")

print("AI model loaded successfully!")

# ------------------------------------------------------------
# 3. PREPARE FAQ TEXT FOR SEMANTIC SEARCH
# ------------------------------------------------------------

faq_texts = [
    item["question"] + " " + item["keywords"]
    for item in faq_data
]

# Convert FAQ text into semantic embeddings
faq_embeddings = model.encode(
    faq_texts,
    convert_to_tensor=True,
    normalize_embeddings=True
)

print("FAQ knowledge base prepared successfully!")

# ------------------------------------------------------------
# 4. QUESTION ANSWERING FUNCTION
# ------------------------------------------------------------

SIMILARITY_THRESHOLD = 0.40

def get_answer(user_question):

    # Convert user question into an embedding
    question_embedding = model.encode(
        user_question,
        convert_to_tensor=True,
        normalize_embeddings=True
    )

    # Calculate semantic similarity
    similarities = util.cos_sim(
        question_embedding,
        faq_embeddings
    )[0]

    # Find the most relevant FAQ
    best_index = torch.argmax(similarities).item()

    best_score = similarities[best_index].item()

    # Check whether the similarity is sufficient
    if best_score < SIMILARITY_THRESHOLD:
        return (
            "Sorry, I could not find a sufficiently relevant answer "
            "in the available FAQ knowledge base. Please contact "
            "the college administration."
        )

    matched_question = faq_data[best_index]["question"]
    answer = faq_data[best_index]["answer"]

    print("\nMatched FAQ:", matched_question)
    print("Similarity Score:", round(best_score, 3))

    return answer

