# 7. CREATE QUESTION ANSWERING FUNCTION

def predict_question(user_question, threshold=None):

    if threshold is None:
        threshold = SIMILARITY_THRESHOLD

    if not user_question or not user_question.strip():

        return {
            "answer": "Please enter a question.",
            "matched_question": "None",
            "category": "None",
            "score": 0.0,
            "accepted": False
        }

    query_embedding = model.encode(
        user_question.strip(),
        convert_to_tensor=True,
        normalize_embeddings=True
    )

    similarities = util.cos_sim(
        query_embedding,
        faq_embeddings
    )[0]

    best_index = torch.argmax(similarities).item()
    best_score = similarities[best_index].item()

    matched_faq = faq_data[best_index]

    if best_score >= threshold:

        return {
            "answer": matched_faq["answer"],
            "matched_question": matched_faq["question"],
            "category": matched_faq["category"],
            "score": round(best_score, 4),
            "accepted": True
        }

    return {
        "answer": (
            "Sorry, I could not find a sufficiently relevant answer "
            "in the available FAQ knowledge base. Please contact "
            "the college administration."
        ),
        "matched_question": matched_faq["question"],
        "category": matched_faq["category"],
        "score": round(best_score, 4),
        "accepted": False
    }

