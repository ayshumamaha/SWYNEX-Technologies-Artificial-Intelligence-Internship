def evaluate_model(threshold=SIMILARITY_THRESHOLD, show=True):

    results = []

    for item in evaluation_data:

        prediction = predict_question(
            item["question"],
            threshold
        )

        expected = item["expected"]

        if expected is None:

            status = (
                "Correct Rejection"
                if not prediction["accepted"]
                else "False Acceptance"
            )

        else:

            status = (
                "Correct Retrieval"
                if prediction["accepted"]
                and prediction["category"] == expected
                else "Incorrect / Rejected"
            )

        results.append({
            "Question": item["question"],
            "Expected": expected if expected else "Out of Scope",
            "Predicted": (
                prediction["category"]
                if prediction["accepted"]
                else "Rejected"
            ),
            "Score": prediction["score"],
            "Evaluation": status
        })

    df = pd.DataFrame(results)

    in_scope = [x for x in evaluation_data if x["expected"]]
    out_scope = [x for x in evaluation_data if x["expected"] is None]

    correct = sum(
        1 for r in results
        if r["Evaluation"] == "Correct Retrieval"
    )

    false_accepts = sum(
        1 for r in results
        if r["Evaluation"] == "False Acceptance"
    )

    correct_rejections = sum(
        1 for r in results
        if r["Evaluation"] == "Correct Rejection"
    )

    incorrect = sum(
        1 for r in results
        if r["Evaluation"] == "Incorrect / Rejected"
    )

    accuracy = correct / len(in_scope) * 100

    false_acceptance_rate = (
        false_accepts / len(out_scope) * 100
    )

    rejection_rate = (
        correct_rejections / len(out_scope) * 100
    )

    if show:

        print("\n" + "=" * 65)
        print("             MODEL EVALUATION RESULTS")
        print("=" * 65)

        print("Similarity Threshold:", threshold)
        print("Total Test Questions:", len(results))
        print("In-scope Questions:", len(in_scope))
        print("Out-of-scope Questions:", len(out_scope))
        print("Correct Retrievals:", correct)
        print("Incorrect / Rejected In-scope:", incorrect)
        print("Correct Rejections:", correct_rejections)
        print("False Acceptances:", false_accepts)

        print("In-scope Retrieval Accuracy:",
              round(accuracy, 2), "%")

        print("False Acceptance Rate:",
              round(false_acceptance_rate, 2), "%")

        print("Out-of-scope Rejection Rate:",
              round(rejection_rate, 2), "%")

        display(df)

    return {
        "accuracy": accuracy,
        "false_acceptance": false_acceptance_rate,
        "rejection_rate": rejection_rate,
        "table": df
    }

